#!/usr/bin/env bash
# PreToolUse (Edit|Write): paths that must not be edited, or only with the operator's say-so.
# Deterministic counterpart of AGENTS.md "Ask Before" and the rules in .claude/rules/.
# Needs jq. Prints a permissionDecision JSON; no output means "no opinion".
set -uo pipefail

command -v jq >/dev/null || { echo "guard-paths: jq not found, path guard skipped" >&2; exit 1; }

input=$(cat)
path=$(jq -r '.tool_input.file_path // empty' <<<"$input")
[ -n "$path" ] || exit 0

root="${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null || pwd)}"
rel="${path#"$root"/}"

decide() { # decision, reason
  jq -n --arg d "$1" --arg r "$2" \
    '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:$d,permissionDecisionReason:$r}}'
  exit 0
}

case "$rel" in
  android/*/api/*.api)
    # The binary-compatibility validator's dump is the record of the public surface. A hand edit
    # makes apiCheck pass without the code matching; the dump is regenerated, never written.
    decide deny "$rel is generated by the binary-compatibility validator. Change the code, then run 'cd android && ./gradlew apiDump' and commit the result (.claude/rules/android-kotlin.md)." ;;
  flutter/*.g.dart|flutter/*.g.kt|flutter/*.g.swift|flutter/*/lib/src/messages.g.dart)
    decide deny "$rel is generated by Pigeon. Edit the pigeon definition and regenerate (.claude/rules/flutter.md)." ;;
  .github/workflows/*|.github/CODEOWNERS|.github/dependabot.yml|SECURITY.md|Package.swift|android/build.gradle.kts|android/gradle/wrapper/*|android/settings.gradle.kts)
    decide ask "$rel is on the AGENTS.md 'Ask Before' list (CI, ownership, security policy, platform floors, plugin versions, dependencies)." ;;
  */build.gradle.kts|*/pubspec.yaml|tools/requirements.txt)
    # A module build file is where a dependency is added; adding one needs approval. Other edits
    # to these files are rare enough that asking is cheaper than missing a dependency.
    decide ask "$rel declares dependencies; adding one is on the AGENTS.md 'Ask Before' list. If this edit adds none, say so." ;;
esac
exit 0
