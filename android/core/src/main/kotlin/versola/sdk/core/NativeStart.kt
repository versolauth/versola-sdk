/**
 * What `/native/start` is asked for: the authorization parameters edge passes through to `/par`,
 * and no other. The list is edge's (`NativeService.PassThroughParameters`), and edge drops
 * anything outside it without an error, so a field here that edge does not forward would be a
 * setting that silently does nothing (`spec/versola-sdk-api.md` section 5).
 *
 * [claims] and [authorizationDetails] are JSON as text, sent as given.
 */
@VersolaInternalApi
public class NativeStartRequest(
    public val redirectUri: String,
    public val scopes: Set<String>,
    public val nonce: String,
    public val acrValues: List<String> = emptyList(),
    public val maxAge: Long? = null,
    public val prompt: String? = null,
    public val loginHint: String? = null,
    public val uiLocales: List<String> = emptyList(),
    public val resources: List<String> = emptyList(),
    public val claims: String? = null,
    public val authorizationDetails: String? = null,
)

/**
 * What `/native/start` answers (`NativeService.StartResponse`). Everything the browser leg and
 * the exchange need; nothing the device decides itself. The PKCE verifier is sealed inside
 * [blob] and never reaches the app.
 */
@VersolaInternalApi
@Serializable
public data class NativeStart(
    @SerialName("client_id")
    public val clientId: String = "",
    @SerialName("request_uri")
    public val requestUri: String = "",
    @SerialName("expires_in")
    public val expiresIn: Long = 0,
    @SerialName("authorization_endpoint")
    public val authorizationEndpoint: String = "",
    /** Generated by edge, not the device: the value the redirect must come back with. */
    @SerialName("state")
    public val state: String = "",
    /** Opaque, AEAD under an edge key; presented back at `/native/complete`. */
    @SerialName("blob")
    public val blob: String = "",
    /**
     * Auth's token endpoint *as auth names it on its mutual-TLS listener* — the `htu` every
     * later proof is signed for, even though the request itself goes to edge. Edge forwards
     * the proof byte for byte and auth verifies it against this URL.
     */
    @SerialName("token_endpoint")
    public val tokenEndpoint: String = "",
    /** Likewise for `/native/revoke`. */
    @SerialName("revocation_endpoint")
    public val revocationEndpoint: String = "",
) {
    /**
     * `spec/errors.md`: an answer the flow cannot use is refused before the browser opens. Every
     * member below is one the sign-in cannot do without, and the three endpoints must be `https`
     * (cleartext to the developer's own machine only): one is opened in the browser and the other
     * two are what the proofs of the session are signed for, so none is taken on trust in the
     * clear. The values themselves stay out of the message.
     */
    internal fun validate(): NativeStart {
        for ((name, value) in listOf(
            "request_uri" to requestUri,
            "state" to state,
            "blob" to blob,
            "authorization_endpoint" to authorizationEndpoint,
            "token_endpoint" to tokenEndpoint,
            "revocation_endpoint" to revocationEndpoint,
        )) {
            if (value.isBlank()) throw malformed("/native/start omitted $name")
        }
        if (expiresIn <= 0) throw malformed("/native/start omitted expires_in, or it is not positive")
        for ((name, value) in listOf(
            "authorization_endpoint" to authorizationEndpoint,
            "token_endpoint" to tokenEndpoint,
            "revocation_endpoint" to revocationEndpoint,
        )) {
            if (!isSecureEndpoint(value)) {
                throw malformed("/native/start answered a $name that is not an https URL (http only on loopback)")
            }
        }
        return this
    }

    private fun malformed(detail: String): VersolaError.Configuration =
        VersolaError.Configuration(VersolaError.Configuration.Detail.TokenResponseMalformed(detail))

    /** Never the blob or the `state`: the blob stands in for the PKCE verifier (`security.md`). */
    override fun toString(): String = "NativeStart(redacted, expiresIn=$expiresIn)"
}

/** Opens the authorization request through edge. */
@VersolaInternalApi
public interface NativeAuthorizationStarter {
    public suspend fun start(request: NativeStartRequest): NativeStart
}

/**
 * The two `htu` values the device signs for after login, kept so a refresh or a revocation in
 * a later process — the common case — does not need a `/native/start` it has no reason to
 * make. Not credential material: URLs edge hands to anyone who asks, kept across logout like
 * discovery metadata.
 */
@VersolaInternalApi
@Serializable
public data class NativeEndpoints(
    @SerialName("token_endpoint")
    public val tokenEndpoint: String,
    @SerialName("revocation_endpoint")
    public val revocationEndpoint: String,
)

@VersolaInternalApi
public interface NativeEndpointsStore {
    public suspend fun load(): NativeEndpoints?
    public suspend fun save(endpoints: NativeEndpoints)
}

/**
 * A plain JSON file, by the same reasoning as [FileProviderMetadataCache].
 *
 * Its failures are typed the way the credential store's I/O failures are (`StorageFailure.toError`
 * in `:storage`): a store that cannot be read or written now is `Recoverable(Network)`, which
 * leaves the grant intact and may be repeated, never an untyped `IOException` and never a verdict
 * on the grant. Only a file that is not what this store writes is a verdict, and only on the file.
 */
@VersolaInternalApi
public class FileNativeEndpointsStore(private val file: File) : NativeEndpointsStore {

    /**
     * Null when there is no file, and when the file holds something this store did not write: that
     * file is deleted, since no retry can read it, and the refresh that asked ends in
     * `CredentialsInvalidated` because the proof it needs cannot be addressed. A read that failed
     * is not a verdict on the file (a transient I/O error, a locked volume): it is raised, the file
     * is left, and the next call reads again. Deleting on it would turn one failed read into a
     * signed-out user.
     */
    override suspend fun load(): NativeEndpoints? = withContext(SdkDispatchers.blocking) {
        val text = try {
            if (!file.exists()) return@withContext null
            file.readText()
        } catch (e: IOException) {
            throw unavailable("read", e)
        }
        try {
            discoveryJson.decodeFromString(NativeEndpoints.serializer(), text)
        } catch (e: SerializationException) {
            file.delete()
            null
        } catch (e: IllegalArgumentException) {
            file.delete()
            null
        }
    }

    /** Throws `Recoverable(Network)` when the endpoints could not be written, a failed rename included. */
    override suspend fun save(endpoints: NativeEndpoints) {
        withContext(SdkDispatchers.blocking) {
            val temporary = File(file.parentFile, file.name + ".tmp")
            try {
                file.parentFile?.mkdirs()
                temporary.writeText(discoveryJson.encodeToString(NativeEndpoints.serializer(), endpoints))
                if (!temporary.renameTo(file)) throw IOException("rename failed")
            } catch (e: IOException) {
                temporary.delete()
                throw unavailable("write", e)
            }
        }
    }

    private fun unavailable(what: String, cause: IOException): VersolaError.Recoverable =
        VersolaError.Recoverable(
            VersolaError.Recoverable.Cause.Network("native endpoints store: $what failed: ${cause.javaClass.simpleName}"),
            cause,
        )
}

/**
 * `POST {edge}/native/start/{clientId}` over OkHttp.
 *
 * The proof on this one request is signed for edge's own URL and answered, when edge demands
 * one, with edge's nonce — the same per-origin cache the authenticated client fills on API
 * calls. The exchange that follows signs for auth's token endpoint instead; see
 * [EdgeNativeTokenClient].
 *
 * One nonce retry and one proof retry, no redirects followed — the same shape as [HttpTokenClient], for the same
 * reasons. Repeated under the operation's retry budget like a pushed authorization request
 * (`spec/retry-policy.md`): a second start creates a second `request_uri` and the first expires
 * unused, so nothing is spent. Every attempt, a repeat and the answer to a nonce challenge alike,
 * mints a new proof: edge refuses a `/native/start` proof it has seen.
 */
@VersolaInternalApi
public class HttpNativeAuthorizationStarter(
    private val configuration: VersolaConfiguration,
    edgeBaseUrl: String,
    httpClient: OkHttpClient,
    private val dpop: DpopProofSource,
) : NativeAuthorizationStarter {

    private val httpClient: OkHttpClient = httpClient.newBuilder()
        .followRedirects(false)
        .followSslRedirects(false)
        .build()

    private val url: String = nativeEndpointUrl(edgeBaseUrl, "start", configuration.clientId)

    override suspend fun start(request: NativeStartRequest): NativeStart {
        val body = FormBody()
            .add("redirect_uri", request.redirectUri)
            .apply { if (request.scopes.isNotEmpty()) add("scope", request.scopes.joinToString(" ")) }
            .add("nonce", request.nonce)
            .apply { if (request.acrValues.isNotEmpty()) add("acr_values", request.acrValues.joinToString(" ")) }
            .apply { request.maxAge?.let { add("max_age", it.toString()) } }
            .apply { request.prompt?.let { add("prompt", it) } }
            .apply { request.loginHint?.let { add("login_hint", it) } }
            .apply { if (request.uiLocales.isNotEmpty()) add("ui_locales", request.uiLocales.joinToString(" ")) }
            // RFC 8707 section 2: one `resource` per value, the only parameter edge lets repeat.
            .apply { request.resources.forEach { add("resource", it) } }
            .apply { request.claims?.let { add("claims", it) } }
            .apply { request.authorizationDetails?.let { add("authorization_details", it) } }
            .toByteArray()

        // The budget and the cooldown are edge's origin's: this request goes to edge, and edge is
        // the one that answers 429 or 503 here (`spec/retry-policy.md`, "Cooldown").
        return retrying(originOf(url)) { startOnce(body) }
    }

    /** One start, with the single nonce retry `spec/retry-policy.md` fixes outside the budget. */
    private suspend fun startOnce(body: ByteArray): NativeStart {
        var nonceRetried = false
        var proofRetried = false
        while (true) {
            val response = attempt(body)
            when (response) {
                is Outcome.Started -> return response.start
                is Outcome.InvalidProof -> {
                    // The same rule as the token endpoint's (`HttpTokenClient`): the one recoverable
                    // cause is clock skew, and `attempt` has already observed the rejection's `Date`,
                    // so the next proof is minted (a new `jti`) with `iat` corrected. A second
                    // refusal means the key is not one the deployment accepts (`spec/errors.md`).
                    if (proofRetried) {
                        throw VersolaError.Reauthenticate(VersolaError.Reauthenticate.Reason.CredentialsInvalidated)
                    }
                    proofRetried = true
                }
                is Outcome.UseDpopNonce -> {
                    if (nonceRetried || response.nonce.isNullOrEmpty()) {
                        throw VersolaError.Recoverable(
                            VersolaError.Recoverable.Cause.NonceLoop(originOf(url)),
                        )
                    }
                    nonceRetried = true
                }
            }
        }
    }

    private suspend fun attempt(body: ByteArray): Outcome {
        val request = Request.Builder()
            .url(url)
            .header("Accept", "application/json")
            .header("DPoP", dpop.proof("POST", url))
            .post(body.toRequestBody(FORM_MEDIA_TYPE))
            .build()
        return withContext(SdkDispatchers.blocking) {
            try {
                httpClient.newCall(request).execute().use { response ->
                    val payload = response.body.string()
                    val nonce = response.header("DPoP-Nonce")
                    dpop.observe(url, response.headers.dateForClockSkew(), nonce)
                    when {
                        response.isSuccessful -> Outcome.Started(parse(payload))
                        // Edge's own challenge: §9's 401 with the error in `WWW-Authenticate`,
                        // the shape its resource proxy uses too (`NativeController.render`).
                        response.code == 401 &&
                            wwwAuthenticateError(response.headers("WWW-Authenticate")) == "use_dpop_nonce" ->
                            Outcome.UseDpopNonce(nonce)
                        isInvalidDpopProof(response.code, payload, response.headers("WWW-Authenticate")) ->
                            Outcome.InvalidProof
                        else -> throw rejected(response.code, payload, response.headers)
                    }
                }
            } catch (e: IOException) {
                throw VersolaError.Recoverable(
                    VersolaError.Recoverable.Cause.Network("native start failed: ${e.message}"),
                    e,
                )
            }
        }
    }

    private fun parse(payload: String): NativeStart = try {
        discoveryJson.decodeFromString(NativeStart.serializer(), payload)
    } catch (e: Exception) {
        throw VersolaError.Configuration(
            VersolaError.Configuration.Detail.TokenResponseMalformed(
                "/native/start answered something other than a start response: ${e.message}",
            ),
            e,
        )
    }.validate()

    /**
     * `spec/errors.md`, native table. A 404 is edge saying it fronts no such client — the
     * client is not `native`, not on a tenant assigned to this edge, or edge has no `native`
     * block — and is the single most likely first-run mistake, so it is named as itself. A
     * 400 is auth's `/par` refusing the pushed request, relayed: `invalid_scope`,
     * `invalid_request`, and the like, all of them `Configuration` because a PAR refusal is
     * the authorization-endpoint refusal the browser would otherwise have shown as a page —
     * surfaced here as an error the app can actually see, which is the whole advantage PAR
     * brings to scenario 17.
     */
    private fun rejected(status: Int, payload: String, headers: okhttp3.Headers): VersolaError {
        if (status == 404) {
            return VersolaError.Configuration(
                EdgeClientUnknown(configuration.clientId),
            )
        }
        if (status in 300..399) {
            return VersolaError.Configuration(
                VersolaError.Configuration.Detail.TokenRequestRejected(
                    "(edge answered HTTP $status to /native/start; redirects are not followed)",
                    null,
                ),
            )
        }
        // Edge's rate limit (429) and overload admission (503) answer with `Retry-After` and no
        // body; read as every client of the core reads them, so the budget waits what edge asked
        // and a wait that does not fit is handed to the app with the value (`spec/errors.md`).
        serverFaultOrNull(status, headers)?.let { return it }
        val error = try {
            discoveryJson.decodeFromString(TokenErrorPayload.serializer(), payload)
        } catch (e: Exception) {
            return VersolaError.Configuration(
                VersolaError.Configuration.Detail.TokenRequestRejected(
                    "(no OAuth error in a HTTP $status response to /native/start)",
                    e.message,
                ),
                e,
            )
        }
        return VersolaError.Configuration(
            VersolaError.Configuration.Detail.AuthorizationRejected(
                error.error.ifBlank { "(no error code in a HTTP $status response to /native/start)" },
                error.errorDescription,
            ),
        )
    }

    /**
     * Edge's `invalid_dpop_proof`, in either shape it takes: a 400 whose JSON body carries the
     * code (what `/native/start` answers, relaying auth) or a 401 with it in `WWW-Authenticate`
     * (edge's own challenge), the two `HttpTokenClient` reads as well.
     */
    private fun isInvalidDpopProof(status: Int, payload: String, wwwAuthenticate: List<String>): Boolean {
        if (status == 401 && wwwAuthenticateError(wwwAuthenticate) == "invalid_dpop_proof") return true
        if (status != 400) return false
        return try {
            discoveryJson.decodeFromString(TokenErrorPayload.serializer(), payload).error == "invalid_dpop_proof"
        } catch (e: Exception) {
            false
        }
    }

    private sealed interface Outcome {
        class Started(val start: NativeStart) : Outcome
        object InvalidProof : Outcome
        class UseDpopNonce(val nonce: String?) : Outcome
    }

    private companion object {
        private val FORM_MEDIA_TYPE = "application/x-www-form-urlencoded".toMediaType()
    }
}

/** `{edge}/native/{endpoint}/{clientId}`, with the client id path-encoded (`EdgeApi.nativeUrl`). */
internal fun nativeEndpointUrl(edgeBaseUrl: String, endpoint: String, clientId: String): String =
    edgeBaseUrl.trimEnd('/') + "/native/" + endpoint + "/" +
        java.net.URLEncoder.encode(clientId, "UTF-8").replace("+", "%20")

/** `https`, or cleartext to the developer's own machine only (`security.md`). */
internal fun isSecureEndpoint(url: String): Boolean {
    val parsed = url.toHttpUrlOrNull() ?: return false
    return parsed.scheme == "https" || parsed.host in LOOPBACK_HOSTS
}

/** OkHttp spells the IPv6 loopback without brackets. */
private val LOOPBACK_HOSTS = setOf("localhost", "127.0.0.1", "::1")
