/**
 * Who the device talks to on the back channel — `/par`, `/token` and `/revoke`.
 *
 * FAPI 2.0 admits confidential clients only, and a mobile app cannot keep a credential. On a
 * tenant with that profile the server refuses a public client at every one of those endpoints
 * (`ClientAuthentication` answers `invalid_client`), so the SDK cannot present itself there.
 * Edge fronts the app instead (versola#420): it authenticates to auth over mutual TLS, pushes
 * the authorization request, redeems the code and refreshes — forwarding the device's DPoP
 * proof unchanged, so every token is still bound to the key in the device's hardware. The
 * browser leg, `/authorize`, goes to auth directly in both cases.
 *
 * Which one applies is a property of the deployment, not of the device, and is not in the
 * OAuth metadata — a tenant's security profile is not advertised — so it is configuration.
 */
public sealed class BackChannel {

    /**
     * The default: the device is a public client of auth and calls `/token` and `/revoke`
     * itself with `client_id` alone. Works on a tenant with the `standard` profile and
     * against any conforming OpenID provider.
     */
    public data object Auth : BackChannel()

    /**
     * Edge's `POST /native/{start,complete,token,revoke}/{clientId}` endpoints front auth.
     * Required on a tenant with the `fapi2` profile — the server's default for a new tenant.
     *
     * Three consequences the configuration must satisfy, each refused at `configure()`:
     * `edgeBaseUrl` is required; the redirect URI must be a verified App Link, because the
     * server registers an edge-fronted native client with `https` redirect URIs only; and
     * the session is key-bound, because every native endpoint demands a DPoP proof —
     * [TokenBinding.Bearer] has nothing to present there.
     */
    public data object Edge : BackChannel()
}

/** What `/native/start` is asked for: the authorization parameters edge passes through to `/par`. */
public class NativeStartRequest(
    public val redirectUri: String,
    public val scopes: Set<String>,
    public val nonce: String,
    public val acrValues: List<String>,
    public val maxAge: Long?,
)

/**
 * What `/native/start` answers (`NativeService.StartResponse`). Everything the browser leg and
 * the exchange need; nothing the device decides itself. The PKCE verifier is sealed inside
 * [blob] and never reaches the app.
 */
@Serializable
public data class NativeStart(
    @SerialName("client_id")
    public val clientId: String = "",
    @SerialName("request_uri")
    public val requestUri: String = "",
    @SerialName("expires_in")
    public val expiresIn: Long = 0,
    @SerialName("authorization_endpoint")
    public val authorizationEndpoint: String = "",
    /** Generated by edge, not the device: the value the redirect must come back with. */
    @SerialName("state")
    public val state: String = "",
    /** Opaque, AEAD under an edge key; presented back at `/native/complete`. */
    @SerialName("blob")
    public val blob: String = "",
    /**
     * Auth's token endpoint *as auth names it on its mutual-TLS listener* — the `htu` every
     * later proof is signed for, even though the request itself goes to edge. Edge forwards
     * the proof byte for byte and auth verifies it against this URL.
     */
    @SerialName("token_endpoint")
    public val tokenEndpoint: String = "",
    /** Likewise for `/native/revoke`. */
    @SerialName("revocation_endpoint")
    public val revocationEndpoint: String = "",
) {
    internal fun validate(): NativeStart {
        for ((name, value) in listOf(
            "request_uri" to requestUri,
            "state" to state,
            "blob" to blob,
            "token_endpoint" to tokenEndpoint,
            "revocation_endpoint" to revocationEndpoint,
        )) {
            if (value.isBlank()) {
                throw VersolaError.Configuration(
                    VersolaError.Configuration.Detail.TokenResponseMalformed("/native/start omitted $name"),
                )
            }
        }
        return this
    }
}

/** Opens the authorization request through edge. */
public interface NativeAuthorizationStarter {
    public suspend fun start(request: NativeStartRequest): NativeStart
}

/**
 * The two `htu` values the device signs for after login, kept so a refresh or a revocation in
 * a later process — the common case — does not need a `/native/start` it has no reason to
 * make. Not credential material: URLs edge hands to anyone who asks, kept across logout like
 * discovery metadata.
 */
@Serializable
public data class NativeEndpoints(
    @SerialName("token_endpoint")
    public val tokenEndpoint: String,
    @SerialName("revocation_endpoint")
    public val revocationEndpoint: String,
)

public interface NativeEndpointsStore {
    public suspend fun load(): NativeEndpoints?
    public suspend fun save(endpoints: NativeEndpoints)
}

/** A plain JSON file, by the same reasoning as [FileProviderMetadataCache]. */
public class FileNativeEndpointsStore(private val file: File) : NativeEndpointsStore {

    override suspend fun load(): NativeEndpoints? = withContext(Dispatchers.IO) {
        if (!file.exists()) return@withContext null
        try {
            discoveryJson.decodeFromString(NativeEndpoints.serializer(), file.readText())
        } catch (e: Exception) {
            file.delete()
            null
        }
    }

    override suspend fun save(endpoints: NativeEndpoints) {
        withContext(Dispatchers.IO) {
            file.parentFile?.mkdirs()
            val temporary = File(file.parentFile, file.name + ".tmp")
            temporary.writeText(discoveryJson.encodeToString(NativeEndpoints.serializer(), endpoints))
            if (!temporary.renameTo(file)) temporary.delete()
        }
    }
}

/**
 * `POST {edge}/native/start/{clientId}` over OkHttp.
 *
 * The proof on this one request is signed for edge's own URL and answered, when edge demands
 * one, with edge's nonce — the same per-origin cache the authenticated client fills on API
 * calls. The exchange that follows signs for auth's token endpoint instead; see
 * [EdgeNativeTokenClient].
 *
 * One nonce retry, no budget of its own, no redirects followed — the same shape as
 * [HttpTokenClient], for the same reasons.
 */
public class HttpNativeAuthorizationStarter(
    private val configuration: VersolaConfiguration,
    edgeBaseUrl: String,
    httpClient: OkHttpClient,
    private val dpop: DpopProofSource,
) : NativeAuthorizationStarter {

    private val httpClient: OkHttpClient = httpClient.newBuilder()
        .followRedirects(false)
        .followSslRedirects(false)
        .build()

    private val url: String = nativeEndpointUrl(edgeBaseUrl, "start", configuration.clientId)

    override suspend fun start(request: NativeStartRequest): NativeStart {
        val body = FormBody()
            .add("redirect_uri", request.redirectUri)
            .apply { if (request.scopes.isNotEmpty()) add("scope", request.scopes.joinToString(" ")) }
            .add("nonce", request.nonce)
            .apply { if (request.acrValues.isNotEmpty()) add("acr_values", request.acrValues.joinToString(" ")) }
            .apply { request.maxAge?.let { add("max_age", it.toString()) } }
            .toByteArray()

        var nonceRetried = false
        while (true) {
            val response = attempt(body)
            when (response) {
                is Outcome.Started -> return response.start
                is Outcome.UseDpopNonce -> {
                    if (nonceRetried || response.nonce.isNullOrEmpty()) {
                        throw VersolaError.Recoverable(
                            VersolaError.Recoverable.Cause.NonceLoop(originOf(url)),
                        )
                    }
                    nonceRetried = true
                }
            }
        }
    }

    private suspend fun attempt(body: ByteArray): Outcome {
        val request = Request.Builder()
            .url(url)
            .header("Accept", "application/json")
            .header("DPoP", dpop.proof("POST", url))
            .post(body.toRequestBody(FORM_MEDIA_TYPE))
            .build()
        return withContext(Dispatchers.IO) {
            try {
                httpClient.newCall(request).execute().use { response ->
                    val payload = response.body.string()
                    val nonce = response.header("DPoP-Nonce")
                    dpop.observe(url, response.header("Date"), nonce)
                    when {
                        response.isSuccessful -> Outcome.Started(parse(payload))
                        // Edge's own challenge: §9's 401 with the error in `WWW-Authenticate`,
                        // the shape its resource proxy uses too (`NativeController.render`).
                        response.code == 401 &&
                            wwwAuthenticateError(response.headers("WWW-Authenticate")) == "use_dpop_nonce" ->
                            Outcome.UseDpopNonce(nonce)
                        else -> throw rejected(response.code, payload)
                    }
                }
            } catch (e: IOException) {
                throw VersolaError.Recoverable(
                    VersolaError.Recoverable.Cause.Network("native start failed: ${e.message}"),
                    e,
                )
            }
        }
    }

    private fun parse(payload: String): NativeStart = try {
        discoveryJson.decodeFromString(NativeStart.serializer(), payload)
    } catch (e: Exception) {
        throw VersolaError.Configuration(
            VersolaError.Configuration.Detail.TokenResponseMalformed(
                "/native/start answered something other than a start response: ${e.message}",
            ),
            e,
        )
    }.validate()

    /**
     * `spec/errors.md`, native table. A 404 is edge saying it fronts no such client — the
     * client is not `native`, not on a tenant assigned to this edge, or edge has no `native`
     * block — and is the single most likely first-run mistake, so it is named as itself. A
     * 400 is auth's `/par` refusing the pushed request, relayed: `invalid_scope`,
     * `invalid_request`, and the like, all of them `Configuration` because a PAR refusal is
     * the authorization-endpoint refusal the browser would otherwise have shown as a page —
     * surfaced here as an error the app can actually see, which is the whole advantage PAR
     * brings to scenario 17.
     */
    private fun rejected(status: Int, payload: String): VersolaError {
        if (status == 404) {
            return VersolaError.Configuration(
                VersolaError.Configuration.Detail.EdgeClientUnknown(configuration.clientId),
            )
        }
        if (status in 300..399) {
            return VersolaError.Configuration(
                VersolaError.Configuration.Detail.TokenRequestRejected(
                    "(edge answered HTTP $status to /native/start; redirects are not followed)",
                    null,
                ),
            )
        }
        if (status >= 500) {
            return VersolaError.Recoverable(
                VersolaError.Recoverable.Cause.Network("edge returned HTTP $status to /native/start"),
            )
        }
        val error = try {
            discoveryJson.decodeFromString(TokenErrorPayload.serializer(), payload)
        } catch (e: Exception) {
            return VersolaError.Configuration(
                VersolaError.Configuration.Detail.TokenRequestRejected(
                    "(no OAuth error in a HTTP $status response to /native/start)",
                    e.message,
                ),
                e,
            )
        }
        return VersolaError.Configuration(
            VersolaError.Configuration.Detail.AuthorizationRejected(
                error.error.ifBlank { "(no error code in a HTTP $status response to /native/start)" },
                error.errorDescription,
            ),
        )
    }

    private sealed interface Outcome {
        class Started(val start: NativeStart) : Outcome
        class UseDpopNonce(val nonce: String?) : Outcome
    }

    private companion object {
        private val FORM_MEDIA_TYPE = "application/x-www-form-urlencoded".toMediaType()
    }
}

/** `{edge}/native/{endpoint}/{clientId}`, with the client id path-encoded (`EdgeApi.nativeUrl`). */
internal fun nativeEndpointUrl(edgeBaseUrl: String, endpoint: String, clientId: String): String =
    edgeBaseUrl.trimEnd('/') + "/native/" + endpoint + "/" +
        java.net.URLEncoder.encode(clientId, "UTF-8").replace("+", "%20")

internal fun originOf(url: String): String = with(java.net.URI(url)) { "$scheme://$authority" }

/**
 * The `error` parameter of a `WWW-Authenticate` challenge, by name and never by scheme —
 * `spec/errors.md`'s rule, applied where the core meets a 401 of its own: edge's nonce
 * demand on `/native/start`, or a relayed one in the same shape.
 */
internal fun wwwAuthenticateError(headers: List<String>): String? {
    val parameter = Regex("""(?:^|[\s,])error\s*=\s*(?:"([^"]*)"|([^\s,]+))""")
    for (header in headers) {
        parameter.find(header)?.let { return it.groups[1]?.value ?: it.groupValues[2] }
    }
    return null
}
