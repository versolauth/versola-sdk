import CryptoKit
import os
import XCTest
@testable import OAuthClient

/// `spec/errors.md`: a DPoP key that is gone while a grant is stored is `Reauthenticate(CredentialsInvalidated)`,
/// raised when a proof is asked for; a key or a store that is merely out of reach (a locked device) is
/// `Recoverable(UnlockRequired)` and never signs the user out.
final class DpopKeyGoneTests: XCTestCase {
    /// A key store whose answers the test scripts: a key, no key, or a read that fails the way a locked Keychain does.
    private final class ScriptedStore: DpopKeyStore {
        private let state = OSAllocatedUnfairLock<(data: Data?, loadFailure: OAuthError?, saves: Int)>(initialState: (nil, nil, 0))
        var saves: Int { state.withLock { $0.saves } }
        var stored: Data? { state.withLock { $0.data } }
        func failLoads(_ error: OAuthError?) { state.withLock { $0.loadFailure = error } }
        func load() throws -> Data? {
            try state.withLock { value in
                if let failure = value.loadFailure { throw failure }
                return value.data
            }
        }
        func save(_ data: Data) throws { state.withLock { $0.data = data; $0.saves += 1 } }
        func delete() throws { state.withLock { $0.data = nil } }
    }

    private func key(_ store: ScriptedStore, grantHeld: @escaping @Sendable () async throws -> Bool) -> SecureEnclaveDpopKey {
        SecureEnclaveDpopKey(store: store, requireHardware: false, secureEnclaveAvailable: false, isGrantHeld: grantHeld)
    }

    private func credentialsInvalidated(_ body: () async throws -> Void) async {
        do {
            try await body()
            XCTFail("expected credentialsInvalidated")
        } catch let error as OAuthError {
            XCTAssertEqual(error, .reauthenticate(.credentialsInvalidated))
        } catch {
            XCTFail("\(error)")
        }
    }

    // MARK: the key is positively gone

    func testAProofForAStoredGrantWhoseKeyIsGoneIsCredentialsInvalidatedAndNoKeyIsMade() async throws {
        let store = ScriptedStore()
        let subject = key(store) { true }

        await credentialsInvalidated { _ = try await subject.provingJwk() }
        await credentialsInvalidated { _ = try await subject.sign(Data("x".utf8)) }

        XCTAssertEqual(store.saves, 0, "a replacement key was generated under the grant")
        XCTAssertNil(store.stored)
    }

    func testTheProofFactoryRefusesToSignWithAReplacementKey() async throws {
        let store = ScriptedStore()
        let factory = DpopProofFactory(key: key(store) { true })

        await credentialsInvalidated { _ = try await factory.proof(method: "POST", url: URL(string: "https://id.example.com/token")!, nonce: nil, accessToken: nil) }
        XCTAssertEqual(store.saves, 0)
    }

    // MARK: a first login still creates a key

    func testAFirstLoginWithNoGrantStoredStillCreatesTheKey() async throws {
        let store = ScriptedStore()
        let subject = key(store) { false }

        _ = try await subject.publicJwk()        // `dpop_jkt`
        let proof = try await DpopProofFactory(key: subject).proof(method: "POST", url: URL(string: "https://id.example.com/token")!, nonce: nil, accessToken: nil)

        XCTAssertFalse(proof.isEmpty)
        XCTAssertEqual(store.saves, 1)
        XCTAssertNotNil(store.stored)
    }

    /// A `login()` binds a new key whatever is stored: the thumbprint and the attestation may generate, which is how a
    /// user whose key was lost signs in again.
    func testTheThumbprintAndTheAttestationMayGenerateEvenWithAGrantStored() async throws {
        let store = ScriptedStore()
        let subject = key(store) { true }

        _ = try await subject.publicJwk()
        _ = try await subject.provingJwk()       // the key exists now: a proof is fine

        XCTAssertEqual(store.saves, 1)
    }

    func testAKeyThatIsThereSignsForAStoredGrant() async throws {
        let store = ScriptedStore()
        _ = try await key(store) { false }.publicJwk()        // generated by an earlier login
        let later = key(store) { true }

        let signature = try await later.sign(Data("x".utf8))

        XCTAssertEqual(signature.count, 64)
        XCTAssertEqual(store.saves, 1)
    }

    // MARK: transient: never a sign-out

    func testAKeychainThatIsLockedWhenTheKeyIsReadIsUnlockRequiredNotCredentialsInvalidated() async throws {
        let store = ScriptedStore()
        _ = try await key(store) { false }.publicJwk()
        store.failLoads(.recoverable(.unlockRequired))
        let subject = key(store) { true }

        for call in [{ _ = try await subject.provingJwk() }, { _ = try await subject.sign(Data("x".utf8)) }] as [@Sendable () async throws -> Void] {
            do {
                try await call()
                XCTFail("read through a locked Keychain")
            } catch let error as OAuthError {
                XCTAssertEqual(error, .recoverable(.unlockRequired))
            }
        }
        XCTAssertNotNil(store.stored, "the key must not be deleted for a read that failed")
        XCTAssertEqual(store.saves, 1)
    }

    func testAGrantProbeThatFailsBecauseTheDeviceIsLockedIsUnlockRequiredAndMakesNoKey() async throws {
        let store = ScriptedStore()        // empty: the key looks gone, but whether a grant is stored cannot be told
        let subject = key(store) { throw OAuthError.recoverable(.unlockRequired) }

        do {
            _ = try await subject.provingJwk()
            XCTFail("signed or generated while the grant could not be probed")
        } catch let error as OAuthError {
            XCTAssertEqual(error, .recoverable(.unlockRequired))
        }
        XCTAssertEqual(store.saves, 0)
    }

    func testAnUnreadableKeyBlobKeepsItsOwnErrorAndIsNotASignOut() async throws {
        let store = ScriptedStore()
        try store.save(Data([0x7F, 1, 2, 3]))        // not a key this SDK wrote
        let subject = key(store) { true }

        do {
            _ = try await subject.provingJwk()
            XCTFail("read an unreadable blob")
        } catch let error as OAuthError {
            guard case .configuration(.hardwareBindingUnavailable) = error else { return XCTFail("\(error)") }
        }
    }
}
