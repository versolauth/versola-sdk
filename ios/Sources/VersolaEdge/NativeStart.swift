import Foundation
import OAuthCore

/// What `/native/start` is asked for: the authorization parameters edge passes through to `/par`,
/// and no other. The list is edge's (`NativeService.PassThroughParameters`), and edge drops anything
/// outside it without an error, so a field here that edge does not forward would be a setting that
/// silently does nothing (`spec/versola-sdk-api.md` section 5).
///
/// `claims` and `authorizationDetails` are JSON as text, sent as given.
package struct NativeStartRequest: Sendable, Equatable {
    package let redirectUri: String
    package let scopes: [String]
    package let nonce: String
    package let acrValues: [String]
    package let maxAge: Int?
    package let prompt: String?
    package let loginHint: String?
    package let uiLocales: [String]
    package let resources: [String]
    package let claims: String?
    package let authorizationDetails: String?

    package init(
        redirectUri: String, scopes: [String], nonce: String, acrValues: [String] = [], maxAge: Int? = nil,
        prompt: String? = nil, loginHint: String? = nil, uiLocales: [String] = [], resources: [String] = [],
        claims: String? = nil, authorizationDetails: String? = nil
    ) {
        self.redirectUri = redirectUri
        self.scopes = scopes
        self.nonce = nonce
        self.acrValues = acrValues
        self.maxAge = maxAge
        self.prompt = prompt
        self.loginHint = loginHint
        self.uiLocales = uiLocales
        self.resources = resources
        self.claims = claims
        self.authorizationDetails = authorizationDetails
    }

    /// The form edge reads, in wire order. Never `client_id`, `state`, `response_type`,
    /// `code_challenge`, `code_challenge_method`, `dpop_jkt` or `id_token_hint`: those are edge's.
    package func formParameters() -> [(String, String)] {
        var form: [(String, String)] = [("redirect_uri", redirectUri)]
        if !scopes.isEmpty { form.append(("scope", scopes.joined(separator: " "))) }
        form.append(("nonce", nonce))
        if !acrValues.isEmpty { form.append(("acr_values", acrValues.joined(separator: " "))) }
        if let maxAge { form.append(("max_age", String(maxAge))) }
        if let prompt { form.append(("prompt", prompt)) }
        if let loginHint { form.append(("login_hint", loginHint)) }
        if !uiLocales.isEmpty { form.append(("ui_locales", uiLocales.joined(separator: " "))) }
        // RFC 8707 section 2: one `resource` per value, the only parameter edge lets repeat.
        for resource in resources { form.append(("resource", resource)) }
        if let claims { form.append(("claims", claims)) }
        if let authorizationDetails { form.append(("authorization_details", authorizationDetails)) }
        return form
    }
}

/// What `/native/start` answers (`NativeService.StartResponse`): everything the browser leg and the
/// exchange need, nothing the device decides itself. The PKCE verifier is sealed inside `blob` and
/// never reaches the app.
package struct NativeStart: Sendable, Equatable, CustomStringConvertible, CustomDebugStringConvertible {
    package let requestUri: String
    package let expiresIn: Int64
    package let authorizationEndpoint: String
    /// Generated by edge, not the device: the value the redirect must come back with.
    package let state: String
    /// Opaque, AEAD under an edge key; presented back at `/native/complete`.
    package let blob: String
    /// Auth's token endpoint as auth names it on its mutual-TLS listener: the `htu` every later
    /// proof is signed for, even though the request itself goes to edge. Edge forwards the proof
    /// byte for byte and auth verifies it against this URL.
    package let tokenEndpoint: String
    /// Likewise for `/native/revoke`.
    package let revocationEndpoint: String

    package init(
        requestUri: String, expiresIn: Int64, authorizationEndpoint: String, state: String, blob: String,
        tokenEndpoint: String, revocationEndpoint: String
    ) {
        self.requestUri = requestUri
        self.expiresIn = expiresIn
        self.authorizationEndpoint = authorizationEndpoint
        self.state = state
        self.blob = blob
        self.tokenEndpoint = tokenEndpoint
        self.revocationEndpoint = revocationEndpoint
    }

    /// Never the blob or the `state`: the blob stands in for the PKCE verifier (`security.md`).
    package var description: String { "NativeStart(redacted, expiresIn=\(expiresIn))" }
    package var debugDescription: String { description }

    /// `spec/errors.md`: an answer the flow cannot use is refused before the browser opens. Every
    /// member is one the sign-in cannot do without, and the three endpoints must be `https`
    /// (cleartext to the developer's own machine only): one is opened in the browser and the other
    /// two are what the proofs of the session are signed for, so none is taken on trust in the
    /// clear. The message names the member and never its value.
    package static func parse(_ body: Data) throws -> NativeStart {
        guard let payload = try? JSONDecoder().decode(Payload.self, from: body) else {
            throw malformed("/native/start answered something other than a start response")
        }
        let members: [(String, String?)] = [
            ("request_uri", payload.requestUri), ("state", payload.state), ("blob", payload.blob),
            ("authorization_endpoint", payload.authorizationEndpoint),
            ("token_endpoint", payload.tokenEndpoint), ("revocation_endpoint", payload.revocationEndpoint),
        ]
        for (name, value) in members where value?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true {
            throw malformed("/native/start omitted \(name)")
        }
        guard let expiresIn = payload.expiresIn, expiresIn > 0 else {
            throw malformed("/native/start omitted expires_in, or it is not positive")
        }
        for (name, value) in members where ["authorization_endpoint", "token_endpoint", "revocation_endpoint"].contains(name) {
            if !isSecureEdgeEndpoint(value ?? "") {
                throw malformed("/native/start answered a \(name) that is not an https URL (http only on loopback)")
            }
        }
        return NativeStart(
            requestUri: payload.requestUri!, expiresIn: expiresIn, authorizationEndpoint: payload.authorizationEndpoint!,
            state: payload.state!, blob: payload.blob!, tokenEndpoint: payload.tokenEndpoint!,
            revocationEndpoint: payload.revocationEndpoint!
        )
    }

    private static func malformed(_ detail: String) -> OAuthError {
        .configuration(.tokenResponseMalformed(detail: detail))
    }

    private struct Payload: Decodable {
        let requestUri: String?
        let expiresIn: Int64?
        let authorizationEndpoint: String?
        let state: String?
        let blob: String?
        let tokenEndpoint: String?
        let revocationEndpoint: String?

        enum CodingKeys: String, CodingKey {
            case requestUri = "request_uri", expiresIn = "expires_in", authorizationEndpoint = "authorization_endpoint"
            case state, blob, tokenEndpoint = "token_endpoint", revocationEndpoint = "revocation_endpoint"
        }
    }
}

/// Opens the authorization request through edge.
package protocol NativeAuthorizationStarter: Sendable {
    func start(_ request: NativeStartRequest) async throws -> NativeStart
}

/// `POST {edge}/native/start/{clientId}` over the core's `HTTPClient`.
///
/// The proof on this one request is signed for edge's own URL and answered, when edge demands one,
/// with edge's nonce, cached under edge's origin like the authenticated session's. The exchange that
/// follows signs for the token endpoint edge answers instead (`EdgeNativeTokenClient`).
///
/// One nonce retry, one `invalid_dpop_proof` retry and no redirects followed, for the reasons
/// `HTTPTokenClient` has. Repeated under
/// the operation's retry budget like a pushed authorization request (`spec/retry-policy.md`): a
/// second start creates a second `request_uri` and the first expires unused, so nothing is spent.
/// Every attempt, a repeat and the answer to a nonce challenge alike, mints a new proof: edge
/// refuses a `/native/start` proof it has seen.
package struct HTTPNativeAuthorizationStarter: NativeAuthorizationStarter {
    private let clientId: String
    private let url: URL
    private let httpClient: HTTPClient
    private let dpop: DpopProofSource

    package init(clientId: String, edgeUrl: URL, httpClient: HTTPClient, dpop: DpopProofSource) throws {
        self.clientId = clientId
        self.url = try edgeNativeUrl(edgeUrl, endpoint: "start", clientId: clientId)
        self.httpClient = httpClient
        self.dpop = dpop
    }

    package func start(_ request: NativeStartRequest) async throws -> NativeStart {
        let body = FormEncoding.body(request.formParameters())
        let origin = DpopOrigin.of(url)
        // The budget and the cooldown are edge's origin's: this request goes to edge, and edge is
        // the one that answers 429 or 503 here (`spec/retry-policy.md`, "Cooldown").
        return try await OperationBudget.run(origin: origin) { try await self.startOnce(body: body, origin: origin) }
    }

    /// One start, with the single nonce retry `spec/retry-policy.md` fixes outside the budget, and the
    /// single `invalid_dpop_proof` retry `spec/errors.md` fixes beside it, as `TokenRequestExecutor` has
    /// both: the response's `Date` is observed on every answer (above), so the retry's proof is minted
    /// from the server's clock, which is what a skewed device needs. A second refusal is the verdict the
    /// executor gives for it, `reauthenticate(.credentialsInvalidated)`: the key does not match what edge
    /// holds for it, and no further proof changes that.
    private func startOnce(body: Data, origin: String) async throws -> NativeStart {
        var nonceAnswered = false
        var proofRetried = false
        while true {
            let proof = try await dpop.proof(method: "POST", url: url, nonce: await dpop.nonce(for: origin), accessToken: nil)
            let response = try await send(body: body, proof: proof)
            await dpop.observe(serverDate: response.header("Date"), age: response.header("Age"), origin: origin)
            let nonce = response.header("DPoP-Nonce")
            if let nonce, !nonce.isEmpty { await dpop.observe(nonce: nonce, origin: origin) }
            if (200..<300).contains(response.statusCode) { return try NativeStart.parse(response.body) }
            // Edge's own challenge: a 401 with the error in `WWW-Authenticate`, the shape its
            // resource proxy uses too.
            if response.statusCode == 401, response.header("WWW-Authenticate").flatMap(wwwAuthenticateError) == "use_dpop_nonce" {
                if nonceAnswered || nonce == nil || nonce!.isEmpty { throw OAuthError.recoverable(.nonceLoop(origin: origin)) }
                nonceAnswered = true
                continue
            }
            // Edge relays auth's refusal of the proof as a 400 with the error in the JSON body, and its own
            // as a 401 with the error in `WWW-Authenticate`; both are the same condition.
            if isInvalidProof(response) {
                if proofRetried { throw OAuthError.reauthenticate(.credentialsInvalidated) }
                proofRetried = true
                continue
            }
            throw rejected(response)
        }
    }

    private func isInvalidProof(_ response: HTTPResponse) -> Bool {
        if response.header("WWW-Authenticate").flatMap(wwwAuthenticateError) == "invalid_dpop_proof" { return true }
        return TokenErrorPayload.parseStrict(response.body)?.error == "invalid_dpop_proof"
    }

    private func send(body: Data, proof: String) async throws -> HTTPResponse {
        let request = HTTPRequest(
            method: .post, url: url,
            headers: ["Accept": "application/json", "Content-Type": "application/x-www-form-urlencoded", "DPoP": proof],
            body: body
        )
        do {
            return try await httpClient.send(request)
        } catch let error as OAuthError {
            throw error
        } catch is CancellationError {
            throw CancellationError()
        } catch {
            throw OAuthError.recoverable(.network(detail: "native start failed", attempts: 1, elapsedMillis: 0))
        }
    }

    /// `spec/errors.md`, native table. A 404 is edge saying it fronts no such client (the client is
    /// not `native`, not on a tenant assigned to this edge, or edge has no `native` block): the single
    /// most likely first-run mistake, so it is named as itself. A 400 is auth's `/par` refusing the
    /// pushed request, relayed, which is `configuration` because a PAR refusal is the authorization
    /// refusal the browser would otherwise have shown as a page.
    private func rejected(_ response: HTTPResponse) -> OAuthError {
        let status = response.statusCode
        if status == 404 { return .configuration(.facade(name: "edge_client_unknown", detail: clientId)) }
        if (300..<400).contains(status) {
            return .configuration(.tokenRequestRejected(code: "(edge answered HTTP \(status) to /native/start; redirects are not followed)", description: nil))
        }
        // Edge's rate limit (429) and overload admission (503) answer with `Retry-After` and no body;
        // read as every client of the core reads them, so the budget waits what edge asked and a wait
        // that does not fit is handed to the app with the value (`spec/errors.md`).
        if let failure = ServerFailure.error(for: response) { return failure }
        guard let error = TokenErrorPayload.parseStrict(response.body) else {
            return .configuration(.tokenRequestRejected(code: "(no OAuth error in a HTTP \(status) response to /native/start)", description: nil))
        }
        return .configuration(.authorizationRejected(
            code: error.error.isEmpty ? "(no error code in a HTTP \(status) response to /native/start)" : error.error,
            description: error.errorDescription
        ))
    }
}
